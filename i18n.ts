/**
 * Safe translation lookup function with multi-tier fallback (lang -> en -> ar -> key)
 */
export function t(lang: Language, key: string): string {
  return translations[lang]?.[key] || translations['en']?.[key] || translations['ar']?.[key] || key;
}

/**
 * Multi-language inline text selector for EN, ES, FR (and AR)
 */
export function trText(lang: Language | string, en: string, es?: string, fr?: string, ar?: string): string {
  if (lang === 'es' && es) return es;
  if (lang === 'fr' && fr) return fr;
  if (lang === 'ar' && ar) return ar;
  return en;
}

